rheld_c = []
for z in CAMP_Z:
    r1, r2, r5 = (A.get("campaign", u, z, 250) for u in (1, 2, 5))
    if not (r2.has_run and r5.has_run and r2.has_hold and r5.has_hold):
        prod_rows.append(" & ".join([num(z), "\\multicolumn{9}{l}{" + pend(f"{r2.status} / {r5.status}") + "}"]) + " \\\\")
        PENDING[f"campaign z {z}"] = f"Kepler {r2.status} ({r2.reason}); explicit {r5.status} ({r5.reason})"
        for k in ("prodZmaxN", "prodZmaxT", "prodWallRatio", "prodWallKepler", "prodWallExplicit",
                  "campHeldOverAnalytic", "campInRet", "anInRetCamp", "campHeldFracAn"):
            put_pending(f"{k}{TOPNAME[z]}", f"campaign z {z} not finished")
        continue
    d2, d5 = A.reduce(r2), A.reduce(r5)
    h2, h5 = A.hold(r2), A.hold(r5)
    tn = TOPNAME[z]
    rn, en, zn, ok = an.profile_compare(d5, d2, "num_dens")
    rT, eT, zT, okT = an.profile_compare(d5, d2, "temp_trans_corr")
    zmn, zmT = float(np.nanmax(np.abs(zn))), float(np.nanmax(np.abs(zT)))
    zn_all.append(zmn)
    zT_all.append(zmT)
    e2 = float((h2.n_esc_direct + h2.n_esc_orbit).sum())
    e5 = float((h5.n_esc_direct + h5.n_esc_orbit).sum())
    in2, in5 = float(h2.n_hold_in.sum()), float(h5.n_hold_in.sum())
    hr = d5.attrs["held_mean"] / d2.attrs["held_mean"]
    held_r.append(hr)
    nr = h5.n_hold_ret.values.astype(float)
    mu, sdi = np.nan_to_num(h5.ret_dt_mean.values), np.nan_to_num(h5.ret_dt_std.values)
    m_ = float((nr * mu).sum() / nr.sum())
    sd = float(np.sqrt(max((nr * (sdi**2 + mu**2)).sum() / nr.sum() - m_**2, 0)))
    w2, w5 = d2.attrs["wall_s"] / 3600, d5.attrs["wall_s"] / 3600
    wall_r.append(w5 / w2)
    # held at t_end against the collisionless held(t) at this top
    i = A.ztop_index(AN, (d2.attrs["r_top"] - SP["R"]) / 1e3)
    t_end = float(d2.time.values[-1])
    h_an = float(np.interp(np.log(t_end), np.log(AN.t.values), AN.held_t.values[i]))
    ha2, ha5 = float(d2.held_t.values[-1]) / h_an, float(d5.held_t.values[-1]) / h_an
    held_an_r += [ha2, ha5]
    # late in/return ratio (t > LATE_T) against the collisionless curve averaged over the same span
    t_a, ratio_a, _ = an.analytic_in_ret(AN, i)
    sel_a = (t_a > LATE_T) & (t_a <= t_end) & np.isfinite(ratio_a)
    ra_late = float(np.mean(ratio_a[sel_a]))
    ir = []
    for h in (h2, h5):
        late = h.time.values > LATE_T
        ir.append(float(h.n_hold_in.values[late].sum() / h.n_hold_ret.values[late].sum()))
    inret_c += ir
    inret_a.append(ra_late)
    if r1.has_run:
        d1 = A.reduce(r1)
        for rr, dd in ((r2, d2), (r5, d5)):
            q, qe, _, _ = an.window_ratio(A.escape_series(rr, "run"), A.escape_series(r1, "run"),
                                          max(dd.attrs["t0"], d1.attrs["t0"]))
            phi_c.append((z, rr.ubc, q, qe))
    put(f"prodZmaxN{tn}", num(zmn, 1))
    put(f"prodZmaxT{tn}", num(zmT, 1))
    put(f"prodWallRatio{tn}", num(w5 / w2, 2))
    put(f"prodWallKepler{tn}", num(w2, 1))
    put(f"prodWallExplicit{tn}", num(w5, 1))
    put(f"campHeldOverAnalytic{tn}", f"{num(ha2, 2)} / {num(ha5, 2)}")
    put(f"campInRet{tn}", f"{num(ir[0], 3)} / {num(ir[1], 3)}")
    put(f"anInRetCamp{tn}", num(ra_late, 3))
    put(f"campHeldFracAn{tn}", num(100 * h_an / float(AN.held_steady[i]), 0))
    rheld_c.append(float((h5.r_held_max.max() - SP["R"]) / 1e3))
    prod_rows.append(" & ".join([
        num(z),
        pm(e5 / e2, e5 / e2 * np.sqrt(1 / e5 + 1 / e2), 3),
        num(hr, 3), num(in5 / in2, 3),
        num(zmn, 1), num(zmT, 1),
        pm(m_, sd, 3),
        sci(float((h5.r_held_max.max() - SP["R"]) / 1e3), 2),
        f"{num(w2, 1)} / {num(w5, 1)}", num(w5 / w2, 2)]) + " \\\\")
    if z == 40000:
        j = np.where(ok)[0][-1]
        put("prodEscRatioTop", pm(e5 / e2, e5 / e2 * np.sqrt(1 / e5 + 1 / e2), 3))
        put("nRatioExplicitTop", pm(rn[j], en[j], 3))
        put("TRatioExplicitTop", pm(rT[j], eT[j], 3))
        put("nZmaxExplicit", num(zmn, 1))
        put("TZmaxExplicit", num(zmT, 1))
        put("prodSimReachedTop", sci(t_end, 1))
        if r1.has_run:   # both ballistic UBCs against the campaign reflect run of the same length (top cell)
            for dd, nm in ((d2, "Kepler"), (d5, "Explicit")):
                cn, cen, _, okc = an.profile_compare(dd, d1, "num_dens")
