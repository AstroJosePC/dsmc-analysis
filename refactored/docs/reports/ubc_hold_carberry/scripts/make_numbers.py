# ---------------------------------------------------------------- formatting (as oh2_escape_rerun)
def sci(x, d=2):
    if x is None or not np.isfinite(x):
        return "--"
    if x == 0:
        return "\\num{0}"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10 ** e
    if round(abs(m), d) >= 10:
        m, e = m / 10, e + 1
    return f"\\sci{{{m:.{d}f}}}{{{str(e).replace('-', '\u2212')}}}"


def num(x, d=0):
    if x is None or not np.isfinite(x):
        return "--"
    s = f"{x:,.{d}f}".replace(",", "\\,").replace("-", "\u2212")
    return f"\\num{{{s}}}"


def pm(x, e, d=2):
    return f"{num(x, d)}\\,$\\pm$\\,{num(e, d)}"


def rng(vals, d=0, sep="--"):
    vals = np.asarray([v for v in vals if v is not None and np.isfinite(v)], dtype=float)
    if len(vals) == 0:
        return "--"
    lo, hi = vals.min(), vals.max()
    if f"{lo:.{d}f}" == f"{hi:.{d}f}":
        return num(lo, d)
    return f"{num(lo, d)}{sep}{num(hi, d)}"


def srng(vals, d=1):
    vals = np.asarray([v for v in vals if np.isfinite(v)], dtype=float)
    lo, hi = vals.min(), vals.max()
    if sci(lo, d) == sci(hi, d):
        return sci(lo, d)
    return f"{sci(lo, d)}--{sci(hi, d)}"


def pend(reason):
    return f"\\pending{{{reason}}}"


def put(name, value):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    M[name] = value


def put_pending(name, reason):
    put(name, pend(reason))
    PENDING[name] = reason


def write(name, rows):
    TABDIR.mkdir(exist_ok=True)
    (TABDIR / name).write_text("% generated by scripts/make_numbers.py -- do not edit\n" + "\n".join(rows) + "\n")


